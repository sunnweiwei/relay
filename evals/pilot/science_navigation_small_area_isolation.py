"""Exact child-process boundaries for Navigation and Small-area solvers."""

from __future__ import annotations

import os
import re
import stat
import subprocess
import sys
import tempfile
from pathlib import Path, PurePosixPath
from typing import Any, Mapping, Sequence


TASKS = {"navigation-sensor-calibration", "small-area-equivalence"}
CANONICAL_PREFIX = "terminal-bench-science/"
BWRAP_PATH = "/opt/relay-tools/bwrap"
SYSTEM_PATHS = (
    "/bin", "/sbin", "/lib", "/lib64", "/etc", "/usr/bin", "/usr/sbin",
    "/usr/lib", "/usr/lib64", "/usr/libexec", "/usr/local", "/usr/share",
    "/usr/include",
)
NAV_ROOT = re.compile(r"/app/navigation-session-[A-Za-z0-9_-]+\Z")
SMALL_ROOT = re.compile(r"/app/sae_v4_case_[A-Za-z0-9_-]+\Z")
OUTPUT_NAMES = {
    "navigation-sensor-calibration": ("calibration.json", "outliers.csv", "trajectory.csv"),
    "small-area-equivalence": (
        "predictive_draws.csv", "survey_estimates.csv", "sampling_covariance.csv",
        "diagnostics.json",
    ),
}
NAV_PRIVACY_PROBE = """
from pathlib import Path

operations = [
    lambda: Path('/tests/cases/alpine/ground_truth/calibration_gt.json').read_bytes(),
    lambda: Path('/tests/.solver-write-probe').write_bytes(b'probe'),
    lambda: Path('/tmp/.navigation-solver-write-probe').write_bytes(b'probe'),
    lambda: Path('/dev/shm/.navigation-solver-write-probe').write_bytes(b'probe'),
]
for operation in operations:
    try:
        operation()
    except OSError:
        continue
    raise SystemExit(1)
"""


class CandidateBoundaryError(RuntimeError):
    """The official child launch does not match an audited solver profile."""


class CandidateLaunch:
    def __init__(self, command: list[str], environment: dict[str, str],
                 fds: tuple[int, ...], dispatcher: Any,
                 output_path: Path | None = None, output_owner: tuple[int, int] | None = None,
                 output_parent: Path | None = None, output_names: tuple[str, ...] = ()):
        self.command = command
        self.environment = environment
        self.pass_fds = fds
        self._dispatcher = dispatcher
        self.output_path = output_path
        self.output_owner = output_owner
        self.output_parent = output_parent
        self.output_names = output_names

    def close(self) -> None:
        dispatcher_fd = self._dispatcher.fileno()
        for descriptor in self.pass_fds:
            if descriptor == dispatcher_fd:
                continue
            try:
                os.close(descriptor)
            except OSError:
                pass
        self._dispatcher.close()

    def export_output_ownership(self, returncode: int | None) -> None:
        """Translate nested user-namespace ownership for the outer fakeroot verifier."""
        if returncode != 0 or self.output_path is None or self.output_owner is None:
            return
        if (self.output_parent is None or self.output_path.parent != self.output_parent
                or self.output_path.name != "output"):
            return
        # Check every existing path component without following links. The
        # expected session root is generated by the official verifier and the
        # output directory is its direct child.
        cursor = self.output_parent
        while True:
            try:
                component = cursor.lstat()
            except FileNotFoundError:
                return
            if stat.S_ISLNK(component.st_mode):
                return
            if cursor == cursor.parent:
                break
            cursor = cursor.parent
        parent_stat = self.output_parent.lstat()
        if not stat.S_ISDIR(parent_stat.st_mode):
            return
        try:
            directory_fd = os.open(
                self.output_path,
                os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0),
            )
        except OSError:
            return
        try:
            if not stat.S_ISDIR(os.fstat(directory_fd).st_mode):
                return
            uid, gid = self.output_owner
            for name in self.output_names:
                if Path(name).name != name or name in {".", ".."}:
                    continue
                try:
                    descriptor = os.open(
                        name, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
                        | getattr(os, "O_CLOEXEC", 0), dir_fd=directory_fd,
                    )
                except OSError:
                    continue
                try:
                    metadata = os.fstat(descriptor)
                    if stat.S_ISREG(metadata.st_mode) and metadata.st_nlink == 1:
                        os.fchown(descriptor, uid, gid)
                finally:
                    os.close(descriptor)
        finally:
            os.close(directory_fd)


def task_slug(task_id: str) -> str:
    if task_id in TASKS:
        return task_id
    if task_id.startswith(CANONICAL_PREFIX) and task_id.count("/") == 1:
        slug = task_id.removeprefix(CANONICAL_PREFIX)
        if slug in TASKS:
            return slug
    raise CandidateBoundaryError(f"No audited solver boundary for {task_id!r}")


def _preexec_is(kwargs: Mapping[str, Any], module: str, name: str) -> bool:
    callback = kwargs.get("preexec_fn")
    code = getattr(callback, "__code__", None)
    return (callback is not None and getattr(callback, "__name__", None) == name
            and getattr(callback, "__module__", None) == module
            and code is not None and code.co_filename.startswith("/tests/"))


def _spec(task_id: str, argv: Any, kwargs: Mapping[str, Any]) -> tuple[str, dict[str, str]] | None:
    try:
        slug = task_slug(task_id)
    except CandidateBoundaryError:
        return None
    if not isinstance(argv, (list, tuple)) or not _preexec_is(
            kwargs, "test_all" if slug == "navigation-sensor-calibration" else "test_state",
            "_demote_solver_process"):
        return None
    args = [os.fspath(item) for item in argv]
    cwd_value = kwargs.get("cwd")
    try:
        cwd = os.fspath(cwd_value)
    except TypeError:
        return None
    environment = kwargs.get("env")
    if not isinstance(environment, Mapping) or not isinstance(cwd, str):
        return None
    if (kwargs.get("stdout") is None or kwargs.get("stderr") is None
            or kwargs.get("shell") or kwargs.get("executable")):
        return None

    if slug == "navigation-sensor-calibration":
        if (len(args) != 7 or args[0] != sys.executable or args[1] != "-B"
                or args[3] != "--input-dir" or args[5] != "--output-dir"
                or kwargs.get("stdin") != subprocess.DEVNULL
                or kwargs.get("start_new_session") is not True
                or kwargs.get("close_fds") is not True or kwargs.get("umask") is not None):
            return None
        solver = PurePosixPath(args[2])
        runtime = solver.parent
        root = runtime.parent
        input_path, output = PurePosixPath(args[4]), PurePosixPath(args[6])
        if (not NAV_ROOT.fullmatch(str(root)) or runtime.name != "runtime"
                or solver.name != "solver.py" or input_path != root / "input"
                or output != root / "output" or PurePosixPath(cwd) != runtime
                or environment.get("HOME") != str(output / ".runtime")
                or environment.get("TMPDIR") != str(output / ".runtime/tmp")
                or environment.get("XDG_CACHE_HOME") != str(output / ".runtime/cache")):
            return None
        return slug, {"root": str(root), "runtime": str(runtime),
                      "candidate": str(solver), "input": str(input_path),
                      "output": str(output), "cwd": str(runtime),
                      "home": str(output / ".runtime"),
                      "tmp": str(output / ".runtime/tmp"),
                      "cache": str(output / ".runtime/cache"), "session": "preserve"}

    if (len(args) != 6 or args[0] != sys.executable
            or kwargs.get("stdin") is not None
            or args[2] != "--data-dir" or args[4] != "--output-dir"
            or kwargs.get("start_new_session") is True):
        return None
    script = PurePosixPath(args[1])
    runtime = script.parent
    case = runtime.parent
    data, output = PurePosixPath(args[3]), PurePosixPath(args[5])
    if (not SMALL_ROOT.fullmatch(str(case)) or runtime.name != "submission"
            or script.name != "solve.py" or data != case / "data"
            or output != case / "output" or PurePosixPath(cwd) != runtime
            or environment.get("HOME") != str(case / "home")
            or environment.get("TMPDIR") != str(case / "home/tmp")
            or environment.get("XDG_CACHE_HOME") != str(case / "home/cache")):
        return None
    return slug, {"root": str(case), "runtime": str(runtime),
                  "candidate": str(script), "input": str(data),
                  "output": str(output), "cwd": str(runtime),
                  "home": str(case / "home"), "tmp": str(case / "home/tmp"),
                  "cache": str(case / "home/cache"), "session": "new"}


def is_candidate(task_id: str, argv: Any, kwargs: Mapping[str, Any]) -> bool:
    return _spec(task_id, argv, kwargs) is not None


def is_privacy_probe(task_id: str, argv: Any, kwargs: Mapping[str, Any]) -> bool:
    """Match only Navigation's trusted child that tests verifier-side isolation."""
    try:
        slug = task_slug(task_id)
    except CandidateBoundaryError:
        return False
    if slug != "navigation-sensor-calibration" or not isinstance(argv, (list, tuple)):
        return False
    args = [os.fspath(item) for item in argv]
    environment = kwargs.get("env")
    return (
        len(args) == 4 and args[0] == sys.executable and args[1:3] == ["-B", "-c"]
        and args[3] == NAV_PRIVACY_PROBE
        and kwargs.get("cwd") == "/app"
        and kwargs.get("stdin") == subprocess.DEVNULL
        and kwargs.get("stdout") == subprocess.DEVNULL
        and kwargs.get("stderr") == subprocess.DEVNULL
        and kwargs.get("start_new_session") is True
        and "timeout" not in kwargs and "check" not in kwargs
        and _preexec_is(kwargs, "test_all", "_demote_solver_process")
        and isinstance(environment, Mapping)
        and set(environment) == {"PATH", "PYTHONHASHSEED"}
    )


def prepare_privacy_probe(
    argv: Sequence[Any], *, environment: Mapping[str, str], uid: int, gid: int,
    source_root: Path = Path("/"), system_root: Path = Path("/"),
    bwrap: str = BWRAP_PATH,
) -> CandidateLaunch:
    """Contain the official probe without exposing verifier files or writable temp roots."""
    args = [os.fspath(item) for item in argv]
    if len(args) != 4 or args[1:3] != ["-B", "-c"] or args[3] != NAV_PRIVACY_PROBE:
        raise CandidateBoundaryError("process is not the exact Navigation privacy probe")
    dispatcher = _dispatcher("navigation-sensor-calibration", args[1:])
    command = [bwrap, "--unshare-user", "--uid", str(uid), "--gid", str(gid),
               "--unshare-pid", "--unshare-ipc", "--unshare-uts", "--unshare-net",
               "--cap-drop", "ALL", "--die-with-parent", "--new-session"]
    system_root = Path(system_root)
    for path in SYSTEM_PATHS:
        host = system_root / path.lstrip("/")
        if host.is_symlink():
            command += ["--symlink", os.readlink(host), path]
        elif host.exists():
            command += ["--ro-bind", str(host), path]
    command += ["--proc", "/proc", "--dev", "/dev", "--dir", "/app",
                "--dir", "/tests", "--chmod", "0555", "/tests",
                "--tmpfs", "/tmp", "--chmod", "0555", "/tmp",
                "--tmpfs", "/dev/shm", "--chmod", "0555", "/dev/shm",
                "--dir", "/opt/relay-isolation",
                "--ro-bind-data", str(dispatcher.fileno()),
                "/opt/relay-isolation/probe_exec.py",
                "--remount-ro", "/", "--remount-ro", "/dev",
                "--chdir", "/app", "--", args[0],
                "/opt/relay-isolation/probe_exec.py", *args[1:]]
    clean = {key: value for key, value in environment.items()
             if key in {"PATH", "PYTHONHASHSEED"}}
    return CandidateLaunch(command, clean, (dispatcher.fileno(),), dispatcher)


def _source(root: Path, target: str, *, directory: bool | None = None) -> Path:
    path = PurePosixPath(target)
    if not path.is_absolute() or ".." in path.parts:
        raise CandidateBoundaryError("candidate path is not absolute and normalized")
    resolved = root / str(path).lstrip("/")
    if resolved.is_symlink() or not resolved.exists():
        raise FileNotFoundError(f"candidate path is unavailable: {target}")
    if directory is True and not resolved.is_dir():
        raise CandidateBoundaryError(f"candidate path must be a directory: {target}")
    if directory is False and not resolved.is_file():
        raise CandidateBoundaryError(f"candidate path must be a file: {target}")
    return resolved


def _safe_tree(root: Path) -> None:
    for path in (root, *root.rglob("*")):
        if path.is_symlink() or not (path.is_dir() or path.is_file()):
            raise CandidateBoundaryError("candidate input tree contains a non-regular entry")


def _dispatcher(slug: str, expected: Sequence[str]) -> Any:
    limits = {
        "RLIMIT_FSIZE": 64 * 1024 * 1024,
        "RLIMIT_NOFILE": 256 if slug == "navigation-sensor-calibration" else 128,
        "RLIMIT_NPROC": 64,
        "RLIMIT_CORE": 0,
    }
    lines = ["import os,resource,sys\n",
             f"if sys.argv[1:] != {list(expected)!r}: raise SystemExit(125)\n"]
    for name, value in limits.items():
        lines.append(f"resource.setrlimit(resource.{name}, ({value}, {value}))\n")
    if slug == "navigation-sensor-calibration":
        lines.append("os.umask(0o077)\n")
    lines.append("os.execv(sys.executable, [sys.executable, *sys.argv[1:]])\n")
    handle = tempfile.TemporaryFile()
    handle.write("".join(lines).encode())
    handle.flush()
    os.lseek(handle.fileno(), 0, os.SEEK_SET)
    return handle


def _clean_environment(environment: Mapping[str, str], paths: Mapping[str, str]) -> dict[str, str]:
    allowed = {
        "PATH", "LANG", "LC_ALL", "PYTHONHASHSEED", "PYTHONNOUSERSITE",
        "PYTHONDONTWRITEBYTECODE", "OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS",
        "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS",
    }
    result = {key: value for key, value in environment.items()
              if key in allowed and not key.startswith(("RELAY_", "APPTAINER", "SINGULARITY"))}
    result["PATH"] = environment.get("PATH", "/usr/local/bin:/usr/bin:/bin")
    result.update(HOME=paths["home"], TMPDIR=paths["tmp"], TMP=paths["tmp"],
                  TEMP=paths["tmp"], XDG_CACHE_HOME=paths["cache"])
    return result


def _build(task_id: str, argv: Sequence[Any], environment: Mapping[str, str],
           cwd: str, uid: int, gid: int, *, source_root: Path, system_root: Path,
           bwrap: str, kwargs: Mapping[str, Any]) -> CandidateLaunch:
    match = _spec(task_id, argv, kwargs)
    if match is None:
        raise CandidateBoundaryError("process is not an audited solver command")
    slug, paths = match
    args = [os.fspath(item) for item in argv]
    candidate_path = _source(source_root,
                             paths["runtime"] if slug == "small-area-equivalence" else paths["candidate"],
                             directory=(slug == "small-area-equivalence"))
    input_path = _source(source_root, paths["input"], directory=True)
    output_path = _source(source_root, paths["output"], directory=True)
    if slug == "small-area-equivalence":
        _safe_tree(candidate_path)
        _source(source_root, paths["candidate"], directory=False)
    else:
        candidate_path = _source(source_root, paths["candidate"], directory=False)
    _safe_tree(input_path)
    fd = os.open(candidate_path, os.O_RDONLY) if slug == "navigation-sensor-calibration" else None
    dispatcher = _dispatcher(slug, args[1:] if slug == "navigation-sensor-calibration" else args[1:])
    descriptors = tuple(value for value in (fd, dispatcher.fileno()) if value is not None)
    system_root = Path(system_root)
    command = [bwrap, "--unshare-user", "--uid", str(uid), "--gid", str(gid),
               "--unshare-pid", "--unshare-ipc", "--unshare-uts", "--unshare-net",
               "--cap-drop", "ALL", "--die-with-parent"]
    if paths["session"] == "new":
        command.append("--new-session")
    for path in SYSTEM_PATHS:
        host = system_root / path.lstrip("/")
        if host.is_symlink():
            command += ["--symlink", os.readlink(host), path]
        elif host.exists():
            command += ["--ro-bind", str(host), path]
    command += ["--proc", "/proc", "--dev", "/dev", "--dir", "/var", "--tmpfs", "/tmp",
                "--tmpfs", "/dev/shm", "--tmpfs", "/var/tmp", "--tmpfs", "/run"]
    command += ["--tmpfs", "/app"]
    root = PurePosixPath(paths["root"])
    directories = [root, PurePosixPath(paths["runtime"]), PurePosixPath(paths["input"]),
                   PurePosixPath(paths["output"]), PurePosixPath(paths["home"]),
                   PurePosixPath(paths["tmp"]), PurePosixPath(paths["cache"]),
                   PurePosixPath("/opt"), PurePosixPath("/opt/relay-isolation")]
    for directory in directories:
        command += ["--dir", str(directory)]
    command += ["--ro-bind", str(input_path), paths["input"]]
    if slug == "navigation-sensor-calibration":
        command += ["--ro-bind-data", str(fd), paths["candidate"]]
    else:
        command += ["--ro-bind", str(candidate_path), paths["runtime"]]
    command += ["--bind", str(output_path), paths["output"]]
    for name in ("home", "tmp", "cache"):
        target = PurePosixPath(paths[name])
        source = _source(source_root, str(target), directory=True)
        command += ["--bind", str(source), str(target)]
    command += ["--ro-bind-data", str(dispatcher.fileno()), "/opt/relay-isolation/solver_exec.py"]
    command += ["--remount-ro", "/", "--remount-ro", "/dev", "--chdir", cwd,
                "--", args[0], "/opt/relay-isolation/solver_exec.py", *args[1:]]
    return CandidateLaunch(command, _clean_environment(environment, paths), descriptors,
                           dispatcher, output_path, (uid, gid),
                           Path(source_root) / paths["root"].lstrip("/"),
                           OUTPUT_NAMES[slug])


def build_candidate_command(
    *, task_id: str, argv: Sequence[Any], kwargs: Mapping[str, Any],
    uid: int, gid: int, source_root: Path = Path("/"), system_root: Path = Path("/"),
    bwrap: str = BWRAP_PATH,
) -> CandidateLaunch:
    """Construct the reviewed per-task mount map and resource-limited exec."""
    if not isinstance(argv, (list, tuple)):
        raise CandidateBoundaryError("candidate argv must be a sequence")
    spec = _spec(task_id, argv, kwargs)
    if spec is None:
        raise CandidateBoundaryError("process is not an audited solver command")
    environment = kwargs.get("env") or os.environ
    cwd = spec[1]["cwd"]
    return _build(task_id, argv, environment, cwd, uid, gid,
                  source_root=Path(source_root), system_root=Path(system_root),
                  bwrap=bwrap, kwargs=kwargs)
